import * as opentype from "opentype.js";

export function buildSpecimen(font: opentype.Font, name: string): string {
  const pangrams = [
    "The quick brown fox jumps over the lazy dog.",
    "Pack my box with five dozen liquor jugs.",
    "Jackdaws love my big sphinx of quartz.",
    "Sphinx of black quartz, judge my vow.",
    "How vexingly quick daft zebras jump!",
    "The five boxing wizards jump quickly.",
  ];

  const sizes = [12, 16, 24, 32, 48, 72];
  const em = font.unitsPerEm || 1000;
  const ascender = font.ascender || 800;
  const descender = font.descender || -200;

  // Generate character map HTML
  let charMap = "";
  for (let i = 32; i <= 126; i++) {
    const char = String.fromCodePoint(i);
    const glyph = font.glyphs.get(i);
    if (glyph && (glyph.unicode ?? 0) > 0) {
      charMap += `<span class="char-cell" title="U+${i.toString(16).toUpperCase().padStart(4, '0')}">${char}</span>`;
    } else {
      charMap += `<span class="char-cell missing"></span>`;
    }
  }

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${name} - Font Specimen</title>
  <style>
    @font-face {
      font-family: '${name}';
      src: url('${name}.woff2') format('woff2'),
           url('${name}.ttf') format('truetype');
      font-weight: normal;
      font-style: normal;
      font-display: swap;
    }
    body { font-family: system-ui, sans-serif; max-width: 900px; margin: 0 auto; padding: 2rem; line-height: 1.6; color: #111; background: #fff; }
    h1, h2, h3 { font-family: '${name}', serif; margin-top: 2rem; margin-bottom: 1rem; }
    .meta { display: grid; grid-template-columns: repeat(auto-fit, minmax(200px, 1fr)); gap: 1rem; margin: 1.5rem 0; padding: 1rem; background: #f5f5f5; border-radius: 8px; }
    .meta dt { font-weight: bold; color: #666; font-size: 0.9rem; }
    .meta dd { margin: 0; font-family: monospace; }
    .sample { font-family: '${name}', serif; margin: 1rem 0; }
    .sample-size { display: block; margin: 1rem 0; }
    .sample-label { font-family: monospace; font-size: 0.85rem; color: #666; margin-bottom: 0.25rem; }
    .pangram { font-family: '${name}', serif; margin: 1rem 0; padding: 1rem; background: #fafafa; border-radius: 8px; }
    .char-map { display: grid; grid-template-columns: repeat(16, 1fr); gap: 4px; margin-top: 1rem; }
    .char-cell { font-family: '${name}', serif; font-size: 1.5rem; text-align: center; padding: 0.5rem; background: #f5f5f5; border-radius: 4px; transition: background 0.2s; }
    .char-cell:hover { background: #e0e0e0; }
    .char-cell.missing { background: #fff; color: #ddd; }
    .watermark { text-align: center; margin-top: 3rem; color: #999; font-size: 0.9rem; }
  </style>
</head>
<body>
  <h1>${name}</h1>

  <dl class="meta">
    <dt>Font Family</dt><dd>${name}</dd>
    <dt>Style</dt><dd>Regular</dd>
    <dt>Units per EM</dt><dd>${em}</dd>
    <dt>Ascender</dt><dd>${ascender}</dd>
    <dt>Descender</dt><dd>${descender}</dd>
    <dt>Glyphs</dt><dd>${font.glyphs.length}</dd>
  </dl>

  <h2>Size Samples</h2>
  ${sizes.map(size => `
    <div class="sample-size">
      <span class="sample-label">${size}px</span>
      <div class="sample" style="font-size: ${size}px;">The quick brown fox jumps over the lazy dog.</div>
    </div>
  `).join("")}

  <h2>Pangrams</h2>
  ${pangrams.map(p => `
    <div class="pangram" style="font-size: 24px;">${p}</div>
  `).join("")}

  <h2>Character Map</h2>
  <div class="char-map">${charMap}</div>

  <div class="watermark">
    Generated by FontKu — <a href="https://github.com/your-repo" target="_blank" rel="noopener">Font Trajectory Designer</a>
  </div>
</body>
</html>`;
}